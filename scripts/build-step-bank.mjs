// Generates src/data/stepBank.{grammar,reading,listening}.ts from scripts/step-src/*.txt
// Run:  node scripts/build-step-bank.mjs
//
// Source format
//   grammar-*.txt  : one question per line
//       question || CORRECT answer || wrong 1 || wrong 2 || wrong 3 || explanation
//   reading-*.txt / listening-*.txt :
//       ### Passage title
//       passage text (blank line = new paragraph; listening: script, "Man:" / "Woman:" for dialogues)
//       Q: question || CORRECT answer || wrong 1 || wrong 2 || wrong 3 || explanation
//   The CORRECT answer is always written first; the script places it at a balanced,
//   pseudo-random position (A/B/C/D) so the answer key is evenly spread.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const srcDir = path.join(root, 'scripts', 'step-src')
const outDir = path.join(root, 'src', 'data')

// ids already used by the hand-written seed questions in stepBank.ts
const START = {
  grammar: { q: 25 },
  reading: { q: 9, p: 3 },
  listening: { q: 10, p: 4 },
}
const TARGET = 200
const SEED_COUNT = { grammar: 24, reading: 8, listening: 9 }

// deterministic RNG so rebuilding never changes the answer key
function rng(seed) {
  let s = seed >>> 0
  return () => {
    s = (s + 0x6d2b79f5) >>> 0
    let t = s
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

function makePositions(n, seed) {
  const rand = rng(seed)
  const out = []
  while (out.length < n) {
    const block = [0, 1, 2, 3]
    for (let i = 3; i > 0; i--) {
      const j = Math.floor(rand() * (i + 1))
      ;[block[i], block[j]] = [block[j], block[i]]
    }
    out.push(...block)
  }
  return out.slice(0, n)
}

function files(prefix) {
  return fs.readdirSync(srcDir).filter(f => f.startsWith(prefix) && f.endsWith('.txt')).sort()
}

function parseQ(raw, where) {
  const parts = raw.split('||').map(s => s.trim())
  if (parts.length !== 6 || parts.some(p => !p)) throw new Error(`Bad question (${where}): ${raw}`)
  const [question, correct, w1, w2, w3, explanation] = parts
  const opts = [correct, w1, w2, w3]
  if (new Set(opts.map(o => o.toLowerCase())).size !== 4) throw new Error(`Duplicate options (${where}): ${raw}`)
  return { question, correct, wrong: [w1, w2, w3], explanation }
}

function place(q, pos) {
  const options = [...q.wrong]
  options.splice(pos, 0, q.correct)
  return { question: q.question, options, correctIndex: pos, explanation: q.explanation }
}

const j = v => JSON.stringify(v)

function header(name, what) {
  return `// AUTO-GENERATED by scripts/build-step-bank.mjs from scripts/step-src/${what}-*.txt — edit the .txt files, then re-run the script.\nimport type { ${name} } from './stepBank'\n\n`
}

// ───────────── grammar ─────────────
function buildGrammar() {
  const qs = []
  for (const f of files('grammar')) {
    fs.readFileSync(path.join(srcDir, f), 'utf8').split('\n').forEach((line, i) => {
      if (!line.trim() || line.startsWith('#')) return
      qs.push(parseQ(line, `${f}:${i + 1}`))
    })
  }
  const pos = makePositions(qs.length, 1001)
  let out = header('StepQuestion', 'grammar') + 'export const GRAMMAR_QUESTIONS: StepQuestion[] = [\n'
  qs.forEach((q, i) => {
    const p = place(q, pos[i])
    out += `  { id: ${j('g' + (START.grammar.q + i))}, section: 'grammar', question: ${j(p.question)}, options: ${j(p.options)}, correctIndex: ${p.correctIndex}, explanation: ${j(p.explanation)} },\n`
  })
  out += ']\n'
  fs.writeFileSync(path.join(outDir, 'stepBank.grammar.ts'), out)
  return qs.length
}

// ───────────── reading / listening ─────────────
function buildPassages(section, idPrefix, qPrefix, exportP, exportQ, seed) {
  const passages = []
  for (const f of files(section)) {
    let cur = null
    fs.readFileSync(path.join(srcDir, f), 'utf8').split('\n').forEach((line, i) => {
      const where = `${f}:${i + 1}`
      if (line.startsWith('### ')) {
        cur = { title: line.slice(4).trim(), text: [], qs: [] }
        passages.push(cur)
      } else if (line.startsWith('Q:')) {
        if (!cur) throw new Error(`Question before passage (${where})`)
        cur.qs.push(parseQ(line.slice(2), where))
      } else if (cur && !line.startsWith('#')) {
        if (cur.qs.length) { if (line.trim()) throw new Error(`Text after questions (${where})`) }
        else cur.text.push(line)
      }
    })
  }
  const total = passages.reduce((a, p) => a + p.qs.length, 0)
  const pos = makePositions(total, seed)
  let pOut = '', qOut = '', qn = START[section].q, k = 0
  passages.forEach((p, pi) => {
    const pid = idPrefix + (START[section].p + pi)
    const text = p.text.join('\n').trim().replace(/\n{2,}/g, '\n\n')
    if (!text || !p.qs.length) throw new Error(`Empty passage: ${p.title}`)
    pOut += `  { id: ${j(pid)}, section: '${section}', title: ${j(p.title)}, text: ${j(text)} },\n`
    p.qs.forEach(q => {
      const x = place(q, pos[k++])
      qOut += `  { id: ${j(qPrefix + qn++)}, section: '${section}', passageId: ${j(pid)}, question: ${j(x.question)}, options: ${j(x.options)}, correctIndex: ${x.correctIndex}, explanation: ${j(x.explanation)} },\n`
    })
  })
  const out = header('StepPassage, StepQuestion', section) +
    `export const ${exportP}: StepPassage[] = [\n${pOut}]\n\nexport const ${exportQ}: StepQuestion[] = [\n${qOut}]\n`
  fs.writeFileSync(path.join(outDir, `stepBank.${section}.ts`), out)
  return { passages: passages.length, questions: total }
}

const g = buildGrammar()
const r = buildPassages('reading', 'r', 'rq', 'READING_PASSAGES', 'READING_QUESTIONS', 2002)
const l = buildPassages('listening', 'l', 'lq', 'LISTENING_PASSAGES', 'LISTENING_QUESTIONS', 3003)

const totals = {
  grammar: g + SEED_COUNT.grammar,
  reading: r.questions + SEED_COUNT.reading,
  listening: l.questions + SEED_COUNT.listening,
}
console.log(`grammar   : ${g} new  → ${totals.grammar} total`)
console.log(`reading   : ${r.questions} new in ${r.passages} passages → ${totals.reading} total`)
console.log(`listening : ${l.questions} new in ${l.passages} scripts  → ${totals.listening} total`)
for (const [k, v] of Object.entries(totals)) {
  if (v !== TARGET) console.warn(`⚠  ${k} has ${v} questions (target ${TARGET})`)
}
